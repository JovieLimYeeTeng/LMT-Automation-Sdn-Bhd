export type Dict = typeof dict.zh;
export type DictKey = keyof Dict;

function applyReplacements(template: string, replacements?: Replacements): string {
  if (!replacements) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    replacements[key] === undefined ? `{${key}}` : String(replacements[key]),
  );
}

export function translate(lang: Lang, key: DictKey, replacements?: Replacements): string {
  const value = dict[lang][key] ?? dict.zh[key] ?? key;
  return applyReplacements(value, replacements);
}

export function makeT(lang: Lang) {
  return (key: DictKey, replacements?: Replacements) => translate(lang, key, replacements);
}

export type T = ReturnType<typeof makeT>;

